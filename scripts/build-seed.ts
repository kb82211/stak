import { writeFileSync } from 'node:fs';

import { achievements, catalogAssets, challenges, lessons, paths } from '../src/content/index.ts';
import { questionsFor } from '../src/content/types.ts';

function quote(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

function json(value: unknown) {
  return `${quote(JSON.stringify(value))}::jsonb`;
}

function textArray(values: string[]) {
  return `array[${values.map(quote).join(', ')}]::text[]`;
}

function answerOf(question: ReturnType<typeof questionsFor>[number]) {
  if (question.type === 'match') {
    return Object.fromEntries(question.pairs.map((pair) => [pair.term, pair.definition]));
  }
  return question.answer;
}

function choicesOf(question: ReturnType<typeof questionsFor>[number]) {
  if (question.type === 'match') return question.pairs;
  return question.choices;
}

const lines: string[] = [
  '-- Generated by scripts/build-seed.ts. Do not edit by hand.',
  'insert into public.learning_paths (id, title, description, lesson_ids, sort_order) values',
];

lines.push(
  paths
    .map(
      (path, index) =>
        `(${quote(path.id)}, ${quote(path.title)}, ${quote(path.description)}, ${textArray(path.lessonIds)}, ${index})`,
    )
    .join(',\n') + ' on conflict (id) do update set title = excluded.title, description = excluded.description, lesson_ids = excluded.lesson_ids, sort_order = excluded.sort_order;',
);

lines.push('insert into public.lessons (id, title, category, premium, sort_order, xp) values');
lines.push(
  lessons
    .map(
      (lesson, index) =>
        `(${quote(lesson.id)}, ${quote(lesson.title)}, ${quote(lesson.category)}, ${lesson.premium}, ${index}, 50)`,
    )
    .join(',\n') + ' on conflict (id) do update set title = excluded.title, category = excluded.category, premium = excluded.premium, sort_order = excluded.sort_order, xp = excluded.xp;',
);

const questions = lessons.flatMap((lesson) =>
  questionsFor(lesson).map((question, index) => ({ lessonId: lesson.id, question, index })),
);
lines.push(
  'insert into public.quiz_questions (id, lesson_id, prompt, kind, choices, answer, explanation, sort_order) values',
);
lines.push(
  questions
    .map(
      ({ lessonId, question, index }) =>
        `(${quote(question.id)}, ${quote(lessonId)}, ${quote(question.prompt)}, ${quote(question.type)}, ${json(choicesOf(question))}, ${json(answerOf(question))}, ${quote(question.explanation)}, ${index})`,
    )
    .join(',\n') +
    ' on conflict (id) do update set lesson_id = excluded.lesson_id, prompt = excluded.prompt, kind = excluded.kind, choices = excluded.choices, answer = excluded.answer, explanation = excluded.explanation, sort_order = excluded.sort_order;',
);

lines.push('insert into public.achievements (id, title, description, xp) values');
lines.push(
  achievements
    .map(
      (item) => `(${quote(item.id)}, ${quote(item.title)}, ${quote(item.description)}, ${item.xp})`,
    )
    .join(',\n') + ' on conflict (id) do update set title = excluded.title, description = excluded.description, xp = excluded.xp;',
);

lines.push('insert into public.challenges (id, type, title, premium, rules) values');
lines.push(
  challenges
    .map(
      (item) =>
        `(${quote(item.id)}, ${quote(item.type)}, ${quote(item.title)}, ${item.premium}, ${item.rules ? json(item.rules) : 'null'})`,
    )
    .join(',\n') +
    ' on conflict (id) do update set type = excluded.type, title = excluded.title, premium = excluded.premium, rules = excluded.rules;',
);

const challengeQuestions = challenges.flatMap((challenge) =>
  challenge.questions.map((question, index) => ({ challengeId: challenge.id, question, index })),
);
lines.push(
  'insert into public.challenge_questions (id, challenge_id, prompt, kind, choices, answer, explanation, sort_order) values',
);
lines.push(
  challengeQuestions
    .map(
      ({ challengeId, question, index }) =>
        `(${quote(question.id)}, ${quote(challengeId)}, ${quote(question.prompt)}, ${quote(question.type)}, ${json(choicesOf(question))}, ${json(answerOf(question))}, ${quote(question.explanation)}, ${index})`,
    )
    .join(',\n') +
    ' on conflict (id) do update set prompt = excluded.prompt, kind = excluded.kind, choices = excluded.choices, answer = excluded.answer, explanation = excluded.explanation, sort_order = excluded.sort_order;',
);

lines.push('insert into public.assets (symbol, name, asset_type, sector, description) values');
lines.push(
  catalogAssets
    .map(
      (asset) =>
        `(${quote(asset.symbol)}, ${quote(asset.name)}, ${quote(asset.assetType)}, ${quote(asset.sector)}, ${quote(asset.description)})`,
    )
    .join(',\n') +
    ' on conflict (symbol) do update set name = excluded.name, asset_type = excluded.asset_type, sector = excluded.sector, description = excluded.description;',
);

writeFileSync(new URL('../supabase/migrations/20261126120100_seed.sql', import.meta.url), `${lines.join('\n')}\n`);
console.log(`Wrote seed for ${lessons.length} lessons, ${questions.length} questions, ${catalogAssets.length} assets.`);
