export function challengeForDate(date: Date) {
  const start = Date.UTC(date.getFullYear(), 0, 0);
  const day = Math.floor((date.getTime() - start) / 86_400_000);
  const types = ['knowledge', 'portfolio', 'literacy', 'research', 'scenario'] as const;
  const type = types[day % types.length];
  const variant = Math.floor(day / types.length) % 2;
  const challenge = challenges.find((item) => item.type === type && item.variant === variant);
  if (!challenge) throw new Error('Challenge catalog is missing a day.');
  return challenge;
}
